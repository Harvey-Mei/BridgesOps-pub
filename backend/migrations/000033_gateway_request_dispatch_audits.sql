CREATE TABLE public.gateway_request_dispatch_audits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    downstream_key_id bigint NOT NULL DEFAULT 0,
    channel_id bigint NOT NULL,
    channel_name_snapshot character varying(256) NOT NULL DEFAULT '',
    group_name character varying(128) NOT NULL DEFAULT '',
    upstream_key_id bigint NOT NULL DEFAULT 0,
    upstream_key_name character varying(128) NOT NULL DEFAULT '',
    model_name character varying(256) NOT NULL DEFAULT '',
    upstream_model_name character varying(256) NOT NULL DEFAULT '',
    reasoning_effort character varying(64) NOT NULL DEFAULT '',
    requested_model_name character varying(256) NOT NULL DEFAULT '',
    requested_reasoning_effort character varying(64) NOT NULL DEFAULT '',
    model_mapping_strategy character varying(32) NOT NULL DEFAULT '',
    model_mapping_details character varying(1024) NOT NULL DEFAULT '',
    method character varying(16) NOT NULL,
    path character varying(512) NOT NULL,
    client_ip character varying(64) NOT NULL DEFAULT '',
    client_ip_source character varying(32) NOT NULL DEFAULT '',
    session_hash character varying(64) NOT NULL DEFAULT '',
    route_reason character varying(32) NOT NULL DEFAULT '',
    route_selection_rank bigint NOT NULL DEFAULT 0,
    session_affinity_origin_request_id bigint NOT NULL DEFAULT 0,
    route_details character varying(4096) NOT NULL DEFAULT '',
    route_attempted_channels character varying(16384) NOT NULL DEFAULT '',
    group_ratio double precision NOT NULL DEFAULT 0,
    completion_ratio double precision NOT NULL DEFAULT 0,
    raw_group_ratio double precision,
    raw_completion_ratio double precision,
    funding_factor double precision,
    cost_basis_version bigint NOT NULL DEFAULT 0,
    cost_basis_source character varying(32) NOT NULL DEFAULT '',
    request_started_at timestamp with time zone NOT NULL,
    stage character varying(16) NOT NULL DEFAULT 'dispatched',
    billing_committed boolean NOT NULL DEFAULT false,
    response_observed_at timestamp with time zone,
    provider_request_id character varying(512) NOT NULL DEFAULT '',
    accepted_at timestamp with time zone,
    accepted_event_type character varying(64) NOT NULL DEFAULT '',
    accepted_object_id character varying(128) NOT NULL DEFAULT '',
    terminal_at timestamp with time zone,
    terminal_kind character varying(64) NOT NULL DEFAULT '',
    request_log_id bigint,
    dispatched_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_gateway_request_dispatch_channel
        CHECK (channel_id > 0),
    CONSTRAINT chk_gateway_request_dispatch_method
        CHECK (length(btrim(method)) > 0),
    CONSTRAINT chk_gateway_request_dispatch_path
        CHECK (length(btrim(path)) > 0),
    CONSTRAINT chk_gateway_request_dispatch_provider_id_bytes
        CHECK (octet_length(provider_request_id) <= 512),
    CONSTRAINT chk_gateway_request_dispatch_stage
        CHECK (stage IN ('dispatched', 'responded', 'accepted', 'completed', 'finalized')),
    CONSTRAINT chk_gateway_request_dispatch_acceptance
        CHECK (
            (accepted_at IS NULL AND accepted_event_type = '' AND accepted_object_id = '')
            OR
            (accepted_at IS NOT NULL AND length(btrim(accepted_event_type)) > 0)
        ),
    CONSTRAINT chk_gateway_request_dispatch_terminal
        CHECK (
            (terminal_at IS NULL AND terminal_kind = '' AND request_log_id IS NULL AND stage NOT IN ('completed', 'finalized'))
            OR
            (terminal_at IS NOT NULL AND length(btrim(terminal_kind)) > 0 AND stage = 'completed' AND request_log_id IS NULL)
            OR
            (terminal_at IS NOT NULL AND length(btrim(terminal_kind)) > 0 AND stage = 'finalized' AND request_log_id IS NOT NULL)
        ),
    CONSTRAINT chk_gateway_request_dispatch_accepted_stage
        CHECK (stage <> 'accepted' OR accepted_at IS NOT NULL),
    CONSTRAINT chk_gateway_request_dispatch_response_stage
        CHECK (stage NOT IN ('responded', 'accepted') OR response_observed_at IS NOT NULL),
    CONSTRAINT chk_gateway_request_dispatch_completed_unaccepted
        CHECK (stage <> 'completed' OR (accepted_at IS NULL AND NOT billing_committed)),
    CONSTRAINT fk_gateway_request_dispatch_log
        FOREIGN KEY (request_log_id) REFERENCES public.gateway_request_logs(id) ON DELETE CASCADE,
    CONSTRAINT uq_gateway_request_dispatch_log
        UNIQUE (request_log_id)
);

CREATE INDEX idx_gateway_request_dispatch_recovery
    ON public.gateway_request_dispatch_audits (dispatched_at, id)
    WHERE terminal_at IS NULL AND (accepted_at IS NOT NULL OR billing_committed);

CREATE INDEX idx_gateway_request_dispatch_unaccepted
    ON public.gateway_request_dispatch_audits (dispatched_at, id)
    WHERE terminal_at IS NULL AND accepted_at IS NULL AND NOT billing_committed;

CREATE INDEX idx_gateway_request_dispatch_retention
    ON public.gateway_request_dispatch_audits (terminal_at, id)
    WHERE terminal_at IS NOT NULL;
