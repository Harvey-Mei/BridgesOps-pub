-- A legacy Sub2API state whose factor came from the advertised path has no
-- durable provider observation to bind after these columns are introduced.
-- Guessing or copying a factor here would manufacture financial evidence. Keep
-- the monetary state unchanged, but fail smart pricing closed until an
-- administrator adopts immutable repair evidence or performs a fresh rebase.
UPDATE public.channel_cost_states AS state
SET status = 'needs_review',
    last_error = CASE
        WHEN btrim(COALESCE(state.last_error, '')) = ''
            THEN 'legacy advertised provider factor requires administrator evidence adoption'
        ELSE state.last_error
    END
FROM public.channels AS channel
WHERE channel.id = state.channel_id
  AND channel.type = 'sub2api'
  AND channel.recharge_multiplier IS NULL
  AND btrim(state.source) = 'advertised'
  AND state.observed_provider_factor IS NULL
  AND state.observed_provider_factor_source = ''
  AND state.observed_provider_factor_sampled_at IS NULL;

