-- Detecting a different provider-authenticated upstream account destroys the
-- channel's accumulated balance and cumulative cost. That clear is a money
-- path, and the binding audit written by 000036 is the only row produced in the
-- same transaction, so it must also freeze the amounts that were zeroed. The
-- columns are nullable because an ordinary binding refresh clears nothing; the
-- shape constraint makes the two cases mutually exclusive and complete.
ALTER TABLE public.gateway_channel_upstream_account_binding_audits
    ADD COLUMN cost_state_cleared boolean NOT NULL DEFAULT false,
    ADD COLUMN previous_channel_identity_revision bigint,
    ADD COLUMN cost_unit_epoch_before bigint,
    ADD COLUMN cost_unit_epoch_after bigint,
    ADD COLUMN cost_state_version_before bigint,
    ADD COLUMN cost_state_version_after bigint,
    ADD COLUMN state_source_before character varying(32) NOT NULL DEFAULT '',
    ADD COLUMN funding_factor_before numeric,
    ADD COLUMN raw_balance_before numeric,
    ADD COLUMN actual_inventory_before numeric,
    ADD COLUMN raw_today_cost_before numeric,
    ADD COLUMN actual_today_cost_before numeric,
    ADD COLUMN raw_total_cost_before numeric,
    ADD COLUMN actual_total_cost_before numeric,
    ADD COLUMN balance_sampled_at_before timestamp with time zone,
    ADD COLUMN cost_sampled_at_before timestamp with time zone,
    ADD CONSTRAINT chk_gateway_channel_account_audit_cost_clear_shape CHECK (
        (
            cost_state_cleared = false
            AND previous_channel_identity_revision IS NULL
            AND cost_unit_epoch_before IS NULL
            AND cost_unit_epoch_after IS NULL
            AND cost_state_version_before IS NULL
            AND cost_state_version_after IS NULL
            AND state_source_before = ''
            AND funding_factor_before IS NULL
            AND raw_balance_before IS NULL
            AND actual_inventory_before IS NULL
            AND raw_today_cost_before IS NULL
            AND actual_today_cost_before IS NULL
            AND raw_total_cost_before IS NULL
            AND actual_total_cost_before IS NULL
            AND balance_sampled_at_before IS NULL
            AND cost_sampled_at_before IS NULL
        ) OR (
            cost_state_cleared = true
            AND previous_upstream_account_id IS NOT NULL
            AND previous_upstream_account_id <> upstream_account_id
            AND previous_channel_identity_revision IS NOT NULL
            AND previous_channel_identity_revision > 0
            AND previous_channel_identity_revision = channel_identity_revision - 1
            AND cost_unit_epoch_before IS NOT NULL
            AND cost_unit_epoch_before > 0
            AND cost_unit_epoch_after = cost_unit_epoch_before + 1
            AND cost_state_version_before IS NOT NULL
            AND cost_state_version_before > 0
            AND cost_state_version_after = cost_state_version_before + 1
            AND length(btrim(state_source_before)) > 0
            AND funding_factor_before IS NOT NULL
            AND funding_factor_before >= 0 AND funding_factor_before < 'Infinity'::numeric
            AND raw_balance_before IS NOT NULL
            AND raw_balance_before >= 0 AND raw_balance_before < 'Infinity'::numeric
            AND actual_inventory_before IS NOT NULL
            AND actual_inventory_before >= 0 AND actual_inventory_before < 'Infinity'::numeric
            AND raw_today_cost_before IS NOT NULL
            AND raw_today_cost_before >= 0 AND raw_today_cost_before < 'Infinity'::numeric
