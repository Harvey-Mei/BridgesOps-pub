-- Whole-channel deletion is a recoverable remote-cleanup workflow.  A normal
-- DELETE request may only prepare this durable identity/epoch fence; it must
-- not cascade local evidence away before the later coordinator has verified
-- every remote managed key.
ALTER TABLE public.channels
    ADD COLUMN deletion_pending boolean NOT NULL DEFAULT false,
    ADD COLUMN deletion_epoch bigint NOT NULL DEFAULT 0,
    ADD COLUMN deletion_identity_revision bigint NOT NULL DEFAULT 0,
    ADD COLUMN deletion_state character varying(32) NOT NULL DEFAULT '',
    ADD COLUMN deletion_requested_at timestamp with time zone;

ALTER TABLE public.channels
    ADD CONSTRAINT chk_channels_channel_deletion_fence
        CHECK (
            (
                NOT deletion_pending
                AND deletion_epoch = 0
                AND deletion_identity_revision = 0
                AND deletion_state = ''
                AND deletion_requested_at IS NULL
            )
            OR
            (
                deletion_pending
                AND deletion_epoch > 0
                AND deletion_epoch < 9223372036854775807
                AND deletion_identity_revision > 0
                AND deletion_identity_revision = upstream_account_identity_revision
                AND deletion_state IN (
                    'pending_remote_cleanup',
                    'manual_review_required',
                    'ready_for_local_finalize'
                )
                AND deletion_requested_at IS NOT NULL
                AND isfinite(deletion_requested_at)
                AND NOT monitor_enabled
                AND NOT latency_probe_enabled
            )
        );

CREATE INDEX idx_channels_deletion_pending
    ON public.channels (deletion_pending, deletion_requested_at, id)
    WHERE deletion_pending;

-- This table intentionally has no FK to channels.  Its tombstone must survive
-- the eventual physical channel deletion so a crash/restart or audit query can
-- still recover the exact remote-cleanup epoch and account identity.
CREATE TABLE public.gateway_channel_deletion_intents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL,
    deletion_epoch bigint NOT NULL,
    channel_identity_revision bigint NOT NULL,
    channel_name_snapshot character varying(128) NOT NULL,
    channel_type_snapshot character varying(32) NOT NULL,
    status character varying(32) NOT NULL DEFAULT 'pending_remote_cleanup',
    last_error text NOT NULL DEFAULT '',
    requested_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_gateway_channel_deletion_intent_epoch
        UNIQUE (channel_id, deletion_epoch),
    CONSTRAINT chk_gateway_channel_deletion_intent_identity
        CHECK (channel_id > 0 AND deletion_epoch > 0 AND channel_identity_revision > 0),
    CONSTRAINT chk_gateway_channel_deletion_intent_snapshot
        CHECK (
            btrim(channel_name_snapshot) <> ''
            AND channel_type_snapshot IN ('newapi', 'sub2api')
            AND isfinite(requested_at)
        ),
    CONSTRAINT chk_gateway_channel_deletion_intent_status
        CHECK (status IN (
            'pending_remote_cleanup',
            'manual_review_required',
            'ready_for_local_finalize',
            'finalized'
        ))
);

CREATE INDEX idx_gateway_channel_deletion_intent_reconcile
    ON public.gateway_channel_deletion_intents (
        channel_id,
        channel_identity_revision,
        status,
        id
    );

-- Every decision about a local upstream-key snapshot is append-only.  These
-- rows deliberately have no FK/CASCADE to either the intent, channel, or
-- upstream group: a physical finalizer must not erase the evidence that shows
-- why a remote key was retained, manually reviewed, or eligible for a later
-- verification step.  This table stores identifiers and hashes only, never a
-- plaintext API key or local ciphertext.
CREATE TABLE public.gateway_channel_deletion_key_audits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_id bigint NOT NULL,
    channel_id bigint NOT NULL,
    deletion_epoch bigint NOT NULL,
    channel_identity_revision bigint NOT NULL,
    local_key_id bigint NOT NULL,
    upstream_group_id bigint,
    presence_generation bigint,
    canonical_group_name character varying(128) NOT NULL DEFAULT '',
    upstream_key_id bigint NOT NULL DEFAULT 0,
    upstream_key_name character varying(128) NOT NULL DEFAULT '',
    key_generation bigint NOT NULL DEFAULT 0,
    ownership_provenance character varying(32) NOT NULL,
    provisioning boolean NOT NULL DEFAULT false,
    disposition character varying(32) NOT NULL,
    reason character varying(64) NOT NULL DEFAULT '',
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_gateway_channel_deletion_key_audit_identity
        CHECK (
            intent_id > 0
            AND channel_id > 0
            AND deletion_epoch > 0
            AND channel_identity_revision > 0
            AND local_key_id > 0
            AND key_generation >= 0
        ),
    CONSTRAINT chk_gateway_channel_deletion_key_audit_group
        CHECK (
            (upstream_group_id IS NULL AND presence_generation IS NULL)
            OR (
                upstream_group_id IS NOT NULL
                AND upstream_group_id > 0
                AND presence_generation IS NOT NULL
                AND presence_generation > 0
            )
        ),
    CONSTRAINT chk_gateway_channel_deletion_key_audit_group_name
        CHECK (
            canonical_group_name = ''
            OR (
                canonical_group_name = lower(btrim(canonical_group_name))
                AND canonical_group_name <> ''
            )
        ),
    CONSTRAINT chk_gateway_channel_deletion_key_audit_ownership
        CHECK (ownership_provenance IN ('created', 'provisioning_claim', 'adopted', 'unknown')),
    CONSTRAINT chk_gateway_channel_deletion_key_audit_disposition
        CHECK (
            (ownership_provenance IN ('created', 'provisioning_claim') AND disposition = 'verify_managed_delete')
            OR (ownership_provenance = 'adopted' AND disposition = 'retain_adopted')
            OR (ownership_provenance = 'unknown' AND disposition = 'manual_review_required')
        )
);

CREATE INDEX idx_gateway_channel_deletion_key_audit_intent
    ON public.gateway_channel_deletion_key_audits (intent_id, channel_id, deletion_epoch, id);

CREATE FUNCTION public.reject_gateway_channel_deletion_key_audit_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'gateway channel deletion key audits are append-only'
        USING ERRCODE = '23514';
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_gateway_channel_deletion_key_audits_append_only
BEFORE UPDATE OR DELETE ON public.gateway_channel_deletion_key_audits
FOR EACH ROW
EXECUTE FUNCTION public.reject_gateway_channel_deletion_key_audit_mutation();
