CREATE TABLE public.gateway_manual_routing_cooldown_audits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_log_id bigint NOT NULL,
    request_first_byte_ms bigint NOT NULL,
    request_created_at timestamp with time zone NOT NULL,
    channel_id bigint NOT NULL,
    channel_name_snapshot character varying(256) NOT NULL DEFAULT '',
    group_name character varying(128) NOT NULL,
    actor character varying(128) NOT NULL,
    idempotency_key character varying(128) NOT NULL,
    duration_seconds bigint NOT NULL,
    previous_cooldown_until timestamp with time zone,
    cooldown_until timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_gateway_manual_cooldown_first_byte
        CHECK (request_first_byte_ms > 30000),
    CONSTRAINT chk_gateway_manual_cooldown_actor
        CHECK (length(btrim(actor)) > 0),
    CONSTRAINT chk_gateway_manual_cooldown_idempotency
        CHECK (length(btrim(idempotency_key)) > 0),
    CONSTRAINT chk_gateway_manual_cooldown_duration
        CHECK (duration_seconds > 0),
    CONSTRAINT chk_gateway_manual_cooldown_until
        CHECK (cooldown_until >= created_at),
    CONSTRAINT uq_gateway_manual_cooldown_idempotency
        UNIQUE (request_log_id, idempotency_key)
);

CREATE INDEX idx_gateway_manual_cooldown_request
    ON public.gateway_manual_routing_cooldown_audits (request_log_id);

CREATE INDEX idx_gateway_manual_cooldown_channel
    ON public.gateway_manual_routing_cooldown_audits (channel_id);

CREATE INDEX idx_gateway_manual_cooldown_created
    ON public.gateway_manual_routing_cooldown_audits (created_at);
