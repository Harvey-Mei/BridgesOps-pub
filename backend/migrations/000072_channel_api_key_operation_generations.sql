-- Keep channel_api_key_operations as the single current row per scope so the
-- previous binary remains compatible if deployment health rollback restores
-- it after this migration. Safely superseded generations are immutable audit
-- snapshots in a separate table.
ALTER TABLE public.channel_api_key_operations
    ADD COLUMN operation_generation integer NOT NULL DEFAULT 1,
    ADD COLUMN channel_identity_revision bigint NOT NULL DEFAULT 0,
    ADD COLUMN upstream_group_id bigint NOT NULL DEFAULT 0,
    ADD COLUMN presence_generation bigint NOT NULL DEFAULT 0,
    ADD COLUMN canonical_group_name character varying(128) NOT NULL DEFAULT '',
    ADD COLUMN absence_confirmation_count integer NOT NULL DEFAULT 0,
    ADD COLUMN absence_first_confirmed_at timestamp with time zone,
    ADD COLUMN absence_last_confirmed_at timestamp with time zone;

CREATE TABLE public.channel_api_key_operation_generations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id bigint NOT NULL,
    channel_id bigint NOT NULL,
    provider character varying(32) NOT NULL,
    scope_hash character varying(64) NOT NULL,
    operation_generation integer NOT NULL,
    request_fingerprint character varying(64) NOT NULL,
    managed_name character varying(256) NOT NULL,
    group_identity character varying(256) NOT NULL,
    custom_key_hash character varying(64),
    status character varying(24) NOT NULL,
    channel_identity_revision bigint NOT NULL,
    upstream_group_id bigint NOT NULL,
    presence_generation bigint NOT NULL,
    canonical_group_name character varying(128) NOT NULL,
    absence_confirmation_count integer NOT NULL,
    absence_first_confirmed_at timestamp with time zone NOT NULL,
    absence_last_confirmed_at timestamp with time zone NOT NULL,
    rejected_post_status integer NOT NULL DEFAULT 0,
    rejected_post_at timestamp with time zone,
    rejected_retry_at timestamp with time zone,
    rejected_retry_count integer NOT NULL DEFAULT 0,
    superseded_by_generation integer NOT NULL,
    superseded_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT fk_channel_api_key_operation_generation_operation
        FOREIGN KEY (operation_id)
        REFERENCES public.channel_api_key_operations(id),
    CONSTRAINT chk_channel_api_key_operation_history_status
        CHECK (status = 'superseded'),
    CONSTRAINT chk_channel_api_key_operation_history_generation
        CHECK (operation_generation > 0 AND superseded_by_generation = operation_generation + 1),
    CONSTRAINT chk_channel_api_key_operation_history_fence
        CHECK (
            channel_identity_revision > 0
            AND upstream_group_id > 0
            AND presence_generation > 0
            AND btrim(canonical_group_name) <> ''
        ),
    CONSTRAINT chk_channel_api_key_operation_history_absence
        CHECK (
            absence_confirmation_count >= 2
            AND absence_last_confirmed_at >= absence_first_confirmed_at
        ),
    CONSTRAINT chk_channel_api_key_operation_history_rejected_post
        CHECK (
            rejected_retry_count >= 0
            AND rejected_post_status IN (0, 429)
            AND (
                (rejected_post_status = 0 AND rejected_post_at IS NULL)
                OR (rejected_post_status = 429 AND rejected_post_at IS NOT NULL)
            )
        ),
    CONSTRAINT chk_channel_api_key_operation_history_times
        CHECK (
            isfinite(absence_first_confirmed_at)
            AND isfinite(absence_last_confirmed_at)
            AND (rejected_post_at IS NULL OR isfinite(rejected_post_at))
            AND (rejected_retry_at IS NULL OR isfinite(rejected_retry_at))
            AND isfinite(superseded_at)
        )
);

CREATE UNIQUE INDEX idx_channel_api_key_operation_generation
    ON public.channel_api_key_operation_generations (operation_id, operation_generation);

CREATE INDEX idx_channel_api_key_operation_generation_scope
    ON public.channel_api_key_operation_generations (
        channel_id, provider, scope_hash, operation_generation
    );

CREATE FUNCTION public.reject_channel_api_key_operation_generation_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'channel api key operation generations are append-only'
        USING ERRCODE = '23514';
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_channel_api_key_operation_generations_append_only
BEFORE UPDATE OR DELETE ON public.channel_api_key_operation_generations
FOR EACH ROW
EXECUTE FUNCTION public.reject_channel_api_key_operation_generation_mutation();

CREATE TRIGGER trg_channel_api_key_operation_generations_reject_truncate
BEFORE TRUNCATE ON public.channel_api_key_operation_generations
FOR EACH STATEMENT
EXECUTE FUNCTION public.reject_channel_api_key_operation_generation_mutation();

ALTER TABLE public.channel_api_key_operations
    ADD CONSTRAINT chk_channel_api_key_operation_generation
        CHECK (operation_generation > 0),
    ADD CONSTRAINT chk_channel_api_key_operation_recovery_fence
        CHECK (
            (
                channel_identity_revision = 0
                AND upstream_group_id = 0
                AND presence_generation = 0
                AND btrim(canonical_group_name) = ''
            )
            OR
            (
                channel_identity_revision > 0
                AND upstream_group_id > 0
                AND presence_generation > 0
                AND btrim(canonical_group_name) <> ''
            )
        ),
    ADD CONSTRAINT chk_channel_api_key_operation_absence_confirmations
        CHECK (
            (
                absence_confirmation_count = 0
                AND absence_first_confirmed_at IS NULL
                AND absence_last_confirmed_at IS NULL
            )
            OR
            (
                absence_confirmation_count > 0
                AND absence_first_confirmed_at IS NOT NULL
                AND absence_last_confirmed_at IS NOT NULL
                AND absence_last_confirmed_at >= absence_first_confirmed_at
            )
        ),
    ADD CONSTRAINT chk_channel_api_key_operation_absence_count_nonnegative
        CHECK (absence_confirmation_count >= 0),
    ADD CONSTRAINT chk_channel_api_key_operation_absence_first_finite
        CHECK (absence_first_confirmed_at IS NULL OR isfinite(absence_first_confirmed_at)),
    ADD CONSTRAINT chk_channel_api_key_operation_absence_last_finite
        CHECK (absence_last_confirmed_at IS NULL OR isfinite(absence_last_confirmed_at));

COMMENT ON COLUMN public.channel_api_key_operations.operation_generation IS
    'Current monotonic generation for this stable operation slot.';
COMMENT ON TABLE public.channel_api_key_operation_generations IS
    'Immutable superseded commit-unknown generations retained for audit lineage.';
