DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM (
            VALUES
                ('channels', 'id'),
                ('channels', 'upstream_account_identity_revision'),
                ('channels', 'cost_unit_epoch'),
                ('channel_cost_states', 'channel_id'),
                ('channel_cost_states', 'version'),
                ('channel_cost_states', 'cost_unit_epoch'),
                ('channel_funding_candidates', 'id'),
                ('channel_funding_candidates', 'channel_id'),
                ('channel_funding_candidates', 'status'),
                ('rate_snapshots', 'channel_id'),
                ('rate_snapshots', 'cost_unit_epoch')
        ) AS required(table_name, column_name)
        WHERE NOT EXISTS (
            SELECT 1
            FROM information_schema.columns AS available
            WHERE available.table_schema = 'public'
              AND available.table_name = required.table_name
              AND available.column_name = required.column_name
        )
    ) THEN
        RAISE EXCEPTION 'migration 000068 requires the channel cost-unit schema';
    END IF;
END;
$$;

CREATE TABLE public.channel_cost_basis_overrides (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL,
    channel_identity_revision bigint NOT NULL,
    channel_name_snapshot character varying(128) NOT NULL,
    channel_type_snapshot character varying(32) NOT NULL,
    idempotency_key character varying(128) NOT NULL,
    request_fingerprint character varying(64) NOT NULL,
    actor character varying(128) NOT NULL,
    note character varying(1024) NOT NULL,
    expected_state_version bigint NOT NULL,
    applied_state_version bigint NOT NULL,
    expected_cost_unit_epoch bigint NOT NULL,
    applied_cost_unit_epoch bigint NOT NULL,
    funding_factor_before numeric NOT NULL,
    funding_factor_after numeric NOT NULL,
    raw_balance numeric NOT NULL,
    actual_inventory_before numeric NOT NULL,
    actual_inventory_after numeric NOT NULL,
    raw_today_cost numeric NOT NULL,
    actual_today_cost_before numeric NOT NULL,
    actual_today_cost_after numeric NOT NULL,
    raw_total_cost numeric NOT NULL,
    actual_total_cost_before numeric NOT NULL,
    actual_total_cost_after numeric NOT NULL,
    state_source_before character varying(32) NOT NULL,
    state_source_after character varying(32) NOT NULL,
    state_status_before character varying(32) NOT NULL,
    state_status_after character varying(32) NOT NULL,
    state_last_error_before text NOT NULL DEFAULT '',
    superseded_candidate_count integer NOT NULL,
    superseded_candidate_digest character varying(64) NOT NULL,
    rate_snapshot_count integer NOT NULL,
    rate_snapshot_digest character varying(64) NOT NULL,
    applied_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_channel_cost_basis_overrides_idempotency
        UNIQUE (channel_id, channel_identity_revision, idempotency_key),
    CONSTRAINT channel_cost_basis_overrides_identity CHECK (
        channel_id > 0
        AND channel_identity_revision > 0
        AND length(btrim(channel_name_snapshot)) > 0
        AND channel_type_snapshot IN ('newapi', 'sub2api')
    ),
    CONSTRAINT channel_cost_basis_overrides_request CHECK (
        length(btrim(idempotency_key)) > 0
        AND request_fingerprint ~ '^[0-9a-f]{64}$'
        AND length(btrim(actor)) > 0
        AND length(btrim(note)) > 0
    ),
    CONSTRAINT channel_cost_basis_overrides_versions CHECK (
        expected_state_version > 0
        AND applied_state_version = expected_state_version + 1
        AND expected_cost_unit_epoch > 0
        AND applied_cost_unit_epoch = expected_cost_unit_epoch + 1
    ),
    CONSTRAINT channel_cost_basis_overrides_factors CHECK (
        funding_factor_before >= 0 AND funding_factor_before < 'Infinity'::numeric
        AND funding_factor_after >= 0 AND funding_factor_after < 'Infinity'::numeric
    ),
    CONSTRAINT channel_cost_basis_overrides_amounts CHECK (
        raw_balance > '-Infinity'::numeric AND raw_balance < 'Infinity'::numeric
        AND actual_inventory_before > '-Infinity'::numeric AND actual_inventory_before < 'Infinity'::numeric
        AND actual_inventory_after > '-Infinity'::numeric AND actual_inventory_after < 'Infinity'::numeric
        AND raw_today_cost >= 0 AND raw_today_cost < 'Infinity'::numeric
        AND actual_today_cost_before >= 0 AND actual_today_cost_before < 'Infinity'::numeric
        AND actual_today_cost_after = actual_today_cost_before
        AND raw_total_cost >= 0 AND raw_total_cost < 'Infinity'::numeric
        AND actual_total_cost_before >= 0 AND actual_total_cost_before < 'Infinity'::numeric
        AND actual_total_cost_after = actual_total_cost_before
    ),
    CONSTRAINT channel_cost_basis_overrides_state CHECK (
        length(btrim(state_source_before)) > 0
        AND state_source_after = 'manual_override'
        AND length(btrim(state_status_before)) > 0
        AND state_status_after = 'ready'
    ),
    CONSTRAINT channel_cost_basis_overrides_rates CHECK (
        rate_snapshot_count >= 0
        AND rate_snapshot_digest ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT channel_cost_basis_overrides_candidates CHECK (
        superseded_candidate_count >= 0
        AND superseded_candidate_digest ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT channel_cost_basis_overrides_applied_at CHECK (isfinite(applied_at))
);

CREATE INDEX idx_channel_cost_basis_overrides_channel_applied
    ON public.channel_cost_basis_overrides (channel_id, applied_at DESC, id DESC);

CREATE FUNCTION public.reject_channel_cost_basis_override_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'channel cost basis override evidence is append-only'
        USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER trg_channel_cost_basis_overrides_append_only
BEFORE UPDATE OR DELETE ON public.channel_cost_basis_overrides
FOR EACH ROW
EXECUTE FUNCTION public.reject_channel_cost_basis_override_mutation();

CREATE TRIGGER trg_channel_cost_basis_overrides_reject_truncate
BEFORE TRUNCATE ON public.channel_cost_basis_overrides
FOR EACH STATEMENT
EXECUTE FUNCTION public.reject_channel_cost_basis_override_mutation();
