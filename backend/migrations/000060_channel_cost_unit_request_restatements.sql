CREATE TABLE public.channel_cost_unit_request_restatements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rebase_id bigint NOT NULL,
    channel_id bigint NOT NULL,
    channel_identity_revision bigint NOT NULL,
    idempotency_key character varying(128) NOT NULL,
    request_fingerprint character varying(64) NOT NULL,
    actor character varying(128) NOT NULL,
    request_log_high_water bigint NOT NULL,
    cost_sampled_at_before timestamp with time zone NOT NULL,
    cost_sampled_at_after timestamp with time zone NOT NULL,
    affected_started_at timestamp with time zone NOT NULL,
    affected_ended_at timestamp with time zone NOT NULL,
    old_funding_factor numeric NOT NULL,
    new_funding_factor numeric NOT NULL,
    expected_population_rows bigint NOT NULL,
    expected_new_ratio_rows bigint NOT NULL,
    expected_old_ratio_rows bigint NOT NULL,
    expected_ratio_mismatch_rows bigint NOT NULL,
    expected_latency_probe_rows bigint NOT NULL,
    expected_restatement_rows bigint NOT NULL,
    expected_already_correct_costed_rows bigint NOT NULL,
    expected_raw_cost_sum numeric NOT NULL,
    expected_recorded_cost_sum numeric NOT NULL,
    expected_corrected_cost_sum numeric NOT NULL,
    expected_undercount_sum numeric NOT NULL,
    expected_already_correct_raw_cost_sum numeric NOT NULL,
    expected_all_costed_raw_cost_sum numeric NOT NULL,
    expected_bucket_count integer NOT NULL,
    expected_bucket_starts jsonb NOT NULL,
    expected_bucket_digest character varying(64) NOT NULL,
    applied_restatement_rows bigint NOT NULL,
    applied_raw_cost_sum numeric NOT NULL,
    applied_recorded_cost_sum numeric NOT NULL,
    applied_corrected_cost_sum numeric NOT NULL,
    applied_undercount_sum numeric NOT NULL,
    applied_cost_basis_version bigint NOT NULL,
    applied_cost_basis_source character varying(32) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_channel_cost_unit_request_restatements_rebase
        FOREIGN KEY (rebase_id) REFERENCES public.channel_cost_unit_rebases(id) ON DELETE RESTRICT,
    CONSTRAINT uq_channel_cost_unit_request_restatements_rebase UNIQUE (rebase_id),
    CONSTRAINT uq_channel_cost_unit_request_restatements_idempotency
        UNIQUE (channel_id, channel_identity_revision, idempotency_key),
    CONSTRAINT channel_cost_unit_request_restatements_identity CHECK (
        channel_id > 0
        AND channel_identity_revision > 0
        AND length(btrim(idempotency_key)) > 0
        AND request_fingerprint ~ '^[0-9a-f]{64}$'
        AND length(btrim(actor)) > 0
    ),
    CONSTRAINT channel_cost_unit_request_restatements_bounds CHECK (
        request_log_high_water > 0
        AND isfinite(cost_sampled_at_before)
        AND isfinite(cost_sampled_at_after)
        AND isfinite(affected_started_at)
        AND isfinite(affected_ended_at)
        AND cost_sampled_at_before < affected_started_at
        AND affected_started_at <= affected_ended_at
        AND affected_ended_at <= cost_sampled_at_after
    ),
    CONSTRAINT channel_cost_unit_request_restatements_factors CHECK (
        old_funding_factor > 0 AND old_funding_factor < 'Infinity'::numeric
        AND new_funding_factor > 0 AND new_funding_factor < 'Infinity'::numeric
        AND old_funding_factor <> new_funding_factor
    ),
    CONSTRAINT channel_cost_unit_request_restatements_counts CHECK (
        expected_population_rows > 0
        AND expected_new_ratio_rows >= 0
        AND expected_old_ratio_rows >= 0
        AND expected_ratio_mismatch_rows >= 0
        AND expected_new_ratio_rows + expected_old_ratio_rows + expected_ratio_mismatch_rows = expected_population_rows
        AND expected_latency_probe_rows >= 0
        AND expected_latency_probe_rows <= expected_population_rows
        AND expected_restatement_rows > 0
        AND expected_restatement_rows <= expected_new_ratio_rows
        AND expected_already_correct_costed_rows >= 0
        AND expected_already_correct_costed_rows <= expected_old_ratio_rows
        AND applied_restatement_rows = expected_restatement_rows
    ),
    CONSTRAINT channel_cost_unit_request_restatements_amounts CHECK (
        expected_raw_cost_sum >= 0 AND expected_raw_cost_sum < 'Infinity'::numeric
        AND expected_recorded_cost_sum >= 0 AND expected_recorded_cost_sum < 'Infinity'::numeric
        AND expected_corrected_cost_sum >= 0 AND expected_corrected_cost_sum < 'Infinity'::numeric
        AND expected_undercount_sum >= 0 AND expected_undercount_sum < 'Infinity'::numeric
        AND expected_already_correct_raw_cost_sum >= 0 AND expected_already_correct_raw_cost_sum < 'Infinity'::numeric
        AND expected_all_costed_raw_cost_sum >= 0 AND expected_all_costed_raw_cost_sum < 'Infinity'::numeric
        AND expected_corrected_cost_sum - expected_recorded_cost_sum = expected_undercount_sum
        AND expected_raw_cost_sum + expected_already_correct_raw_cost_sum = expected_all_costed_raw_cost_sum
        AND round(applied_raw_cost_sum, scale(expected_raw_cost_sum)) = expected_raw_cost_sum
        AND round(applied_recorded_cost_sum, scale(expected_recorded_cost_sum)) = expected_recorded_cost_sum
        AND round(applied_corrected_cost_sum, scale(expected_corrected_cost_sum)) = expected_corrected_cost_sum
        AND round(applied_undercount_sum, scale(expected_undercount_sum)) = expected_undercount_sum
    ),
    CONSTRAINT channel_cost_unit_request_restatements_buckets CHECK (
        expected_bucket_count > 0
        AND jsonb_typeof(expected_bucket_starts) = 'array'
        AND jsonb_array_length(expected_bucket_starts) = expected_bucket_count
        AND expected_bucket_digest ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT channel_cost_unit_request_restatements_basis CHECK (
        applied_cost_basis_version > 0
        AND length(btrim(applied_cost_basis_source)) > 0
        AND isfinite(created_at)
    )
);

CREATE INDEX idx_channel_cost_unit_request_restatements_channel_created
    ON public.channel_cost_unit_request_restatements (channel_id, created_at DESC, id DESC);

CREATE TABLE public.channel_cost_unit_request_restatement_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restatement_id bigint NOT NULL,
    request_log_id bigint NOT NULL,
    request_created_at timestamp with time zone NOT NULL,
    raw_cost numeric NOT NULL,
    raw_group_ratio numeric NOT NULL,
    raw_completion_ratio numeric,
    cost_before numeric NOT NULL,
    cost_after numeric NOT NULL,
    group_ratio_before numeric NOT NULL,
    group_ratio_after numeric NOT NULL,
    completion_ratio_before numeric NOT NULL,
    completion_ratio_after numeric NOT NULL,
    funding_factor_before numeric NOT NULL,
    funding_factor_after numeric NOT NULL,
    cost_basis_version_before bigint NOT NULL,
    cost_basis_version_after bigint NOT NULL,
    cost_basis_source_before character varying(32) NOT NULL,
    cost_basis_source_after character varying(32) NOT NULL,
    cost_source character varying(32) NOT NULL,
    cost_status character varying(16) NOT NULL,
    route_reason character varying(32) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_channel_cost_unit_request_restatement_items_operation
        FOREIGN KEY (restatement_id) REFERENCES public.channel_cost_unit_request_restatements(id) ON DELETE RESTRICT,
    CONSTRAINT uq_channel_cost_unit_request_restatement_items_request
        UNIQUE (restatement_id, request_log_id),
    CONSTRAINT channel_cost_unit_request_restatement_items_shape CHECK (
        request_log_id > 0
        AND isfinite(request_created_at)
        AND raw_cost >= 0 AND raw_cost < 'Infinity'::numeric
        AND raw_group_ratio >= 0 AND raw_group_ratio < 'Infinity'::numeric
        AND (raw_completion_ratio IS NULL OR (raw_completion_ratio >= 0 AND raw_completion_ratio < 'Infinity'::numeric))
        AND cost_before >= 0 AND cost_before < 'Infinity'::numeric
        AND cost_after >= 0 AND cost_after < 'Infinity'::numeric
        AND group_ratio_before >= 0 AND group_ratio_before < 'Infinity'::numeric
        AND group_ratio_after >= 0 AND group_ratio_after < 'Infinity'::numeric
        AND completion_ratio_before >= 0 AND completion_ratio_before < 'Infinity'::numeric
        AND completion_ratio_after >= 0 AND completion_ratio_after < 'Infinity'::numeric
        AND funding_factor_before > 0 AND funding_factor_before < 'Infinity'::numeric
        AND funding_factor_after > 0 AND funding_factor_after < 'Infinity'::numeric
        AND cost_basis_version_after > cost_basis_version_before
        AND length(btrim(cost_basis_source_after)) > 0
        AND length(btrim(cost_status)) > 0
        AND isfinite(created_at)
    )
);

CREATE INDEX idx_channel_cost_unit_request_restatement_items_request
    ON public.channel_cost_unit_request_restatement_items (request_log_id, restatement_id);

