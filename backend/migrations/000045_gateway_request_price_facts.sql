    identity_changed boolean;
BEGIN
    identity_changed :=
        NEW.channel_id IS DISTINCT FROM OLD.channel_id
        OR NEW.group_name IS DISTINCT FROM OLD.group_name
        OR NEW.upstream_key_id IS DISTINCT FROM OLD.upstream_key_id
        OR NEW.upstream_key_name IS DISTINCT FROM OLD.upstream_key_name
        OR NEW.ownership_provenance IS DISTINCT FROM OLD.ownership_provenance
        OR NEW.provisioning IS DISTINCT FROM OLD.provisioning
        OR NEW.api_key_cipher IS DISTINCT FROM OLD.api_key_cipher
        OR NEW.api_key_prefix IS DISTINCT FROM OLD.api_key_prefix;

    IF identity_changed THEN
        IF OLD.key_generation >= 9223372036854775807 THEN
            RAISE EXCEPTION 'gateway upstream key generation is exhausted'
                USING ERRCODE = '22003';
        END IF;
        NEW.key_generation := OLD.key_generation + 1;
    ELSIF NEW.key_generation IS DISTINCT FROM OLD.key_generation THEN
        RAISE EXCEPTION 'gateway upstream key generation is database managed'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

