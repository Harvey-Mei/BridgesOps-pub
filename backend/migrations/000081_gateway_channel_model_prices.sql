-- Provider-published prices are scoped to the exact channel account and cost
-- unit that produced them. Historical requests never read this mutable table;
-- dispatch freezes a copy in gateway_request_price_facts first.
ALTER TABLE public.channels
    ADD COLUMN model_price_observed_at timestamp(6) with time zone;

CREATE TABLE public.gateway_channel_model_prices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL,
    channel_identity_revision bigint NOT NULL,
    cost_unit_epoch bigint NOT NULL,
    upstream_group_id bigint NOT NULL,
    gateway_upstream_group_id bigint NOT NULL,
    upstream_group_presence_generation bigint NOT NULL,
    upstream_group_name character varying(128) NOT NULL,
    group_ratio double precision NOT NULL,
    model_name character varying(256) NOT NULL,
    input_unit_price_usd double precision NOT NULL,
    output_unit_price_usd double precision NOT NULL,
    cache_read_unit_price_usd double precision,
    cache_write_unit_price_usd double precision,
    long_context_basis character varying(32) NOT NULL DEFAULT '',
    long_context_threshold_tokens bigint,
    long_context_input_unit_price_usd double precision,
    long_context_output_unit_price_usd double precision,
    long_context_cache_read_unit_price_usd double precision,
    long_context_cache_write_unit_price_usd double precision,
    source_version character varying(128) NOT NULL DEFAULT '',
    source_checksum character varying(64) NOT NULL,
    source_observed_at timestamp(6) with time zone NOT NULL,
    created_at timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_gateway_channel_model_prices_channel
        FOREIGN KEY (channel_id) REFERENCES public.channels(id) ON DELETE CASCADE,
    CONSTRAINT fk_gateway_channel_model_prices_group
        FOREIGN KEY (gateway_upstream_group_id, channel_id)
        REFERENCES public.gateway_upstream_groups(id, channel_id) ON DELETE CASCADE,
    CONSTRAINT uq_gateway_channel_model_prices UNIQUE (channel_id, upstream_group_name, model_name),
    CONSTRAINT chk_gateway_channel_model_prices_scope
        CHECK (
            channel_id > 0
            AND channel_identity_revision > 0
            AND cost_unit_epoch > 0
            AND upstream_group_id >= 0
            AND gateway_upstream_group_id > 0
            AND upstream_group_presence_generation > 0
        ),
    CONSTRAINT chk_gateway_channel_model_prices_group
        CHECK (
            upstream_group_name = lower(btrim(upstream_group_name))
            AND upstream_group_name <> ''
            AND group_ratio >= 0
            AND group_ratio::text NOT IN ('NaN', 'Infinity', '-Infinity')
        ),
    CONSTRAINT chk_gateway_channel_model_prices_model
        CHECK (model_name = btrim(model_name) AND model_name <> ''),
    CONSTRAINT chk_gateway_channel_model_prices_values
        CHECK (
            input_unit_price_usd >= 0
            AND output_unit_price_usd >= 0
            AND input_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            AND output_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            AND (cache_read_unit_price_usd IS NULL OR (
                cache_read_unit_price_usd >= 0
                AND cache_read_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            ))
            AND (cache_write_unit_price_usd IS NULL OR (
                cache_write_unit_price_usd >= 0
                AND cache_write_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            ))
            AND (long_context_input_unit_price_usd IS NULL OR (
                long_context_input_unit_price_usd >= 0
                AND long_context_input_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            ))
            AND (long_context_output_unit_price_usd IS NULL OR (
                long_context_output_unit_price_usd >= 0
                AND long_context_output_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            ))
            AND (long_context_cache_read_unit_price_usd IS NULL OR (
                long_context_cache_read_unit_price_usd >= 0
                AND long_context_cache_read_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            ))
            AND (long_context_cache_write_unit_price_usd IS NULL OR (
                long_context_cache_write_unit_price_usd >= 0
                AND long_context_cache_write_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            ))
        ),
    CONSTRAINT chk_gateway_channel_model_prices_long_context
        CHECK (
            (
                long_context_basis = ''
                AND long_context_threshold_tokens IS NULL
                AND long_context_input_unit_price_usd IS NULL
                AND long_context_output_unit_price_usd IS NULL
                AND long_context_cache_read_unit_price_usd IS NULL
                AND long_context_cache_write_unit_price_usd IS NULL
            )
            OR
            (
                long_context_basis = 'whole_request'
                AND long_context_threshold_tokens > 0
                AND long_context_threshold_tokens < 9223372036854775807
                AND long_context_input_unit_price_usd IS NOT NULL
                AND long_context_output_unit_price_usd IS NOT NULL
            )
        ),
    CONSTRAINT chk_gateway_channel_model_prices_source
        CHECK (
            source_version = btrim(source_version)
            AND source_checksum = lower(source_checksum)
            AND source_checksum ~ '^[0-9a-f]{64}$'
        ),
    CONSTRAINT chk_gateway_channel_model_prices_times
        CHECK (
            isfinite(source_observed_at)
            AND isfinite(created_at)
            AND isfinite(updated_at)
            AND updated_at >= created_at
        )
);

CREATE INDEX idx_gateway_channel_model_prices_lookup
    ON public.gateway_channel_model_prices (
        channel_id,
        channel_identity_revision,
        cost_unit_epoch,
        gateway_upstream_group_id,
        upstream_group_presence_generation,
        upstream_group_name,
        model_name
    );
