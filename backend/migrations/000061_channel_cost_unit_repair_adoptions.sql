CREATE FUNCTION public.validate_channel_cost_unit_repair_adoption_restatement()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    adoption_id bigint;
    matching_rows bigint;
BEGIN
    IF TG_TABLE_NAME = 'channel_cost_unit_repair_adoptions' THEN
        adoption_id := NEW.id;
    ELSE
        adoption_id := NEW.repair_adoption_id;
        IF adoption_id IS NULL THEN
            RETURN NULL;
        END IF;
    END IF;

    SELECT count(*)
    INTO matching_rows
    FROM public.channel_cost_unit_repair_adoptions AS adoption
    JOIN public.channel_cost_unit_request_restatements AS restatement
      ON restatement.repair_adoption_id = adoption.id
    WHERE adoption.id = adoption_id
      AND restatement.rebase_id IS NULL
      AND restatement.channel_id = adoption.channel_id
      AND restatement.channel_identity_revision = adoption.channel_identity_revision
      AND restatement.idempotency_key = adoption.idempotency_key
      AND restatement.request_fingerprint = adoption.request_fingerprint
      AND restatement.actor = adoption.actor
      AND restatement.request_log_high_water = adoption.request_log_high_water
      AND restatement.cost_sampled_at_before = adoption.cost_sampled_at_before
      AND restatement.cost_sampled_at_after = adoption.cost_sampled_at_after
      AND restatement.affected_started_at = adoption.affected_started_at
      AND restatement.affected_ended_at = adoption.affected_ended_at
      AND restatement.old_funding_factor = adoption.funding_factor_before
      AND restatement.new_funding_factor = adoption.funding_factor_after
      AND restatement.applied_cost_basis_version = adoption.state_version
      AND restatement.applied_cost_basis_source = 'cost_unit_repair_adoption';

    IF matching_rows <> 1 THEN
        RAISE EXCEPTION 'repair adoption must have exactly one matching request restatement'
            USING ERRCODE = '23514',
                  CONSTRAINT = 'channel_cost_unit_repair_adoption_restatement_consistency';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_channel_cost_unit_repair_adoptions_require_restatement
AFTER INSERT ON public.channel_cost_unit_repair_adoptions
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION public.validate_channel_cost_unit_repair_adoption_restatement();

CREATE CONSTRAINT TRIGGER trg_channel_cost_unit_repair_restatements_match_adoption
AFTER INSERT ON public.channel_cost_unit_request_restatements
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
WHEN (NEW.repair_adoption_id IS NOT NULL)
EXECUTE FUNCTION public.validate_channel_cost_unit_repair_adoption_restatement();
