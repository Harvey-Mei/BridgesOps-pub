-- A repair adoption records an emergency repair that already happened before
-- the canonical rebase machinery existed. It is deliberately not a rebase: it
-- neither changes channel monetary state nor advances its version/epoch.
CREATE TABLE public.channel_cost_unit_repair_adoptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL,
    channel_identity_revision bigint NOT NULL,
    channel_name_snapshot character varying(128) NOT NULL,
    channel_type_snapshot character varying(32) NOT NULL,
    account_identity_fingerprint character varying(64) NOT NULL,
    account_identity_fingerprint_version bigint NOT NULL,
    account_identity_fingerprint_source character varying(128) NOT NULL,
    account_identity_fingerprint_observed_at timestamp with time zone NOT NULL,
    idempotency_key character varying(128) NOT NULL,
    request_fingerprint character varying(64) NOT NULL,
    preview_digest character varying(64) NOT NULL,
    actor character varying(128) NOT NULL,
    source_event_high_water bigint NOT NULL,
    reset_event_id bigint NOT NULL,
    correction_event_id bigint NOT NULL,
    reset_event_snapshot jsonb NOT NULL,
    correction_event_snapshot jsonb NOT NULL,
    source_events_digest character varying(64) NOT NULL,
    state_version bigint NOT NULL,
    cost_unit_epoch bigint NOT NULL,
    state_source_at_adoption character varying(32) NOT NULL,
    state_status_at_adoption character varying(32) NOT NULL,
    cost_state_snapshot jsonb NOT NULL,
    cost_state_digest character varying(64) NOT NULL,
    channel_projection_snapshot jsonb NOT NULL,
    channel_projection_digest character varying(64) NOT NULL,
    cost_sampled_at_before timestamp with time zone NOT NULL,
    cost_sampled_at_after timestamp with time zone NOT NULL,
    affected_started_at timestamp with time zone NOT NULL,
    affected_ended_at timestamp with time zone NOT NULL,
    request_log_high_water bigint NOT NULL,
    previous_provider_factor numeric NOT NULL,
    current_provider_factor numeric NOT NULL,
    factor_source character varying(32) NOT NULL,
    funding_factor_before numeric NOT NULL,
    funding_factor_after numeric NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_channel_cost_unit_repair_adoptions_reset_event
        FOREIGN KEY (reset_event_id, channel_id)
        REFERENCES public.channel_funding_events(id, channel_id) ON DELETE RESTRICT,
    CONSTRAINT fk_channel_cost_unit_repair_adoptions_correction_event
        FOREIGN KEY (correction_event_id, channel_id)
        REFERENCES public.channel_funding_events(id, channel_id) ON DELETE RESTRICT,
    CONSTRAINT uq_channel_cost_unit_repair_adoptions_idempotency
        UNIQUE (channel_id, channel_identity_revision, idempotency_key),
    CONSTRAINT uq_channel_cost_unit_repair_adoptions_source_events
        UNIQUE (channel_id, reset_event_id, correction_event_id),
    CONSTRAINT channel_cost_unit_repair_adoptions_identity CHECK (
        channel_id > 0
        AND channel_identity_revision > 0
        AND length(btrim(channel_name_snapshot)) > 0
        AND channel_type_snapshot = 'sub2api'
        AND account_identity_fingerprint ~ '^[0-9a-f]{64}$'
        AND account_identity_fingerprint_version > 0
        AND length(btrim(account_identity_fingerprint_source)) > 0
        AND isfinite(account_identity_fingerprint_observed_at)
    ),
    CONSTRAINT channel_cost_unit_repair_adoptions_request CHECK (
        length(btrim(idempotency_key)) > 0
        AND request_fingerprint ~ '^[0-9a-f]{64}$'
        AND preview_digest ~ '^[0-9a-f]{64}$'
        AND length(btrim(actor)) > 0
    ),
    CONSTRAINT channel_cost_unit_repair_adoptions_source_event_ids CHECK (
        source_event_high_water > 0
        AND reset_event_id > 0
        AND correction_event_id > reset_event_id
        AND correction_event_id <= source_event_high_water
    ),
    CONSTRAINT channel_cost_unit_repair_adoptions_source_event_snapshots CHECK (
        jsonb_typeof(reset_event_snapshot) = 'object'
        AND jsonb_typeof(correction_event_snapshot) = 'object'
        AND reset_event_snapshot ?& ARRAY[
            'id', 'channel_id', 'kind', 'funding_factor_before',
            'funding_factor_after', 'effective_at', 'created_at'
        ]
        AND correction_event_snapshot ?& ARRAY[
            'id', 'channel_id', 'kind', 'funding_factor_before',
            'funding_factor_after', 'effective_at', 'created_at'
        ]
        AND reset_event_snapshot->>'id' IS NOT DISTINCT FROM reset_event_id::text
        AND correction_event_snapshot->>'id' IS NOT DISTINCT FROM correction_event_id::text
        AND reset_event_snapshot->>'channel_id' IS NOT DISTINCT FROM channel_id::text
        AND correction_event_snapshot->>'channel_id' IS NOT DISTINCT FROM channel_id::text
        AND reset_event_snapshot->>'kind' IS NOT DISTINCT FROM 'denomination_reset'
        AND correction_event_snapshot->>'kind' IS NOT DISTINCT FROM 'denomination_cost_fix'
        AND jsonb_typeof(reset_event_snapshot->'funding_factor_before') IS NOT DISTINCT FROM 'number'
        AND jsonb_typeof(reset_event_snapshot->'funding_factor_after') IS NOT DISTINCT FROM 'number'
        AND jsonb_typeof(correction_event_snapshot->'funding_factor_before') IS NOT DISTINCT FROM 'number'
        AND jsonb_typeof(correction_event_snapshot->'funding_factor_after') IS NOT DISTINCT FROM 'number'
        AND (reset_event_snapshot->>'funding_factor_before')::numeric = funding_factor_before
        AND (reset_event_snapshot->>'funding_factor_after')::numeric = funding_factor_after
        AND (correction_event_snapshot->>'funding_factor_before')::numeric = funding_factor_after
        AND (correction_event_snapshot->>'funding_factor_after')::numeric = funding_factor_after
        AND jsonb_typeof(reset_event_snapshot->'effective_at') IS NOT DISTINCT FROM 'string'
        AND jsonb_typeof(correction_event_snapshot->'effective_at') IS NOT DISTINCT FROM 'string'
        AND (reset_event_snapshot->>'effective_at')::timestamp with time zone
            IS NOT DISTINCT FROM affected_ended_at
        AND (correction_event_snapshot->>'effective_at')::timestamp with time zone
            IS NOT DISTINCT FROM cost_sampled_at_after
        AND jsonb_typeof(reset_event_snapshot->'created_at') IS NOT DISTINCT FROM 'string'
        AND jsonb_typeof(correction_event_snapshot->'created_at') IS NOT DISTINCT FROM 'string'
        AND isfinite((reset_event_snapshot->>'created_at')::timestamp with time zone)
        AND isfinite((correction_event_snapshot->>'created_at')::timestamp with time zone)
        AND source_events_digest ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT channel_cost_unit_repair_adoptions_state_anchor CHECK (
        state_version > 0
        AND cost_unit_epoch > 0
        AND state_source_at_adoption = 'manual_denomination_reset'
        AND state_status_at_adoption = 'ready'
        AND jsonb_typeof(cost_state_snapshot) = 'object'
        AND jsonb_typeof(channel_projection_snapshot) = 'object'
        AND cost_state_snapshot ?& ARRAY[
            'channel_id', 'version', 'cost_unit_epoch', 'source', 'status', 'funding_factor',
            'raw_balance', 'actual_inventory', 'balance_sampled_at',
            'raw_today_cost', 'actual_today_cost', 'raw_total_cost', 'actual_total_cost', 'cost_sampled_at',
            'observed_provider_factor', 'observed_provider_factor_source',
            'observed_provider_factor_sampled_at'
        ]
        AND cost_state_snapshot->>'channel_id' IS NOT DISTINCT FROM channel_id::text
        AND cost_state_snapshot->>'version' IS NOT DISTINCT FROM state_version::text
        AND cost_state_snapshot->>'cost_unit_epoch' IS NOT DISTINCT FROM cost_unit_epoch::text
        AND cost_state_snapshot->>'source' IS NOT DISTINCT FROM state_source_at_adoption
        AND cost_state_snapshot->>'status' IS NOT DISTINCT FROM state_status_at_adoption
        AND jsonb_typeof(cost_state_snapshot->'funding_factor') IS NOT DISTINCT FROM 'number'
        AND (cost_state_snapshot->>'funding_factor')::numeric = funding_factor_after
        AND CASE jsonb_typeof(cost_state_snapshot->'raw_balance')
            WHEN 'number' THEN (cost_state_snapshot->>'raw_balance')::numeric >= 0
                AND (cost_state_snapshot->>'raw_balance')::numeric < 'Infinity'::numeric
            ELSE false
        END
        AND CASE jsonb_typeof(cost_state_snapshot->'actual_inventory')
            WHEN 'number' THEN (cost_state_snapshot->>'actual_inventory')::numeric >= 0
                AND (cost_state_snapshot->>'actual_inventory')::numeric < 'Infinity'::numeric
            ELSE false
        END
        AND CASE jsonb_typeof(cost_state_snapshot->'raw_today_cost')
            WHEN 'number' THEN (cost_state_snapshot->>'raw_today_cost')::numeric >= 0
                AND (cost_state_snapshot->>'raw_today_cost')::numeric < 'Infinity'::numeric
            ELSE false
        END
        AND CASE jsonb_typeof(cost_state_snapshot->'actual_today_cost')
            WHEN 'number' THEN (cost_state_snapshot->>'actual_today_cost')::numeric >= 0
                AND (cost_state_snapshot->>'actual_today_cost')::numeric < 'Infinity'::numeric
            ELSE false
        END
        AND CASE jsonb_typeof(cost_state_snapshot->'raw_total_cost')
            WHEN 'number' THEN (cost_state_snapshot->>'raw_total_cost')::numeric >= 0
                AND (cost_state_snapshot->>'raw_total_cost')::numeric < 'Infinity'::numeric
            ELSE false
        END
        AND CASE jsonb_typeof(cost_state_snapshot->'actual_total_cost')
            WHEN 'number' THEN (cost_state_snapshot->>'actual_total_cost')::numeric >= 0
                AND (cost_state_snapshot->>'actual_total_cost')::numeric < 'Infinity'::numeric
            ELSE false
        END
        AND CASE jsonb_typeof(cost_state_snapshot->'balance_sampled_at')
            WHEN 'null' THEN true
            WHEN 'string' THEN isfinite(
                (cost_state_snapshot->>'balance_sampled_at')::timestamp with time zone
            )
            ELSE false
        END
        AND CASE jsonb_typeof(cost_state_snapshot->'cost_sampled_at')
            WHEN 'null' THEN true
            WHEN 'string' THEN isfinite(
                (cost_state_snapshot->>'cost_sampled_at')::timestamp with time zone
            )
            ELSE false
        END
        AND jsonb_typeof(cost_state_snapshot->'observed_provider_factor') IS NOT DISTINCT FROM 'number'
        AND abs(
            (cost_state_snapshot->>'observed_provider_factor')::numeric
            - current_provider_factor
        ) <= GREATEST(
            abs((cost_state_snapshot->>'observed_provider_factor')::numeric),
            abs(current_provider_factor),
            1::numeric
        ) * 0.000000000001::numeric
        AND cost_state_snapshot->>'observed_provider_factor_source' IS NOT DISTINCT FROM factor_source
        AND jsonb_typeof(cost_state_snapshot->'observed_provider_factor_sampled_at') IS NOT DISTINCT FROM 'string'
        AND isfinite((cost_state_snapshot->>'observed_provider_factor_sampled_at')::timestamp with time zone)
        AND (cost_state_snapshot->>'observed_provider_factor_sampled_at')::timestamp with time zone
            >= cost_sampled_at_after
        AND channel_projection_snapshot ?& ARRAY[
            'id', 'upstream_account_identity_revision', 'cost_unit_epoch',
            'raw_last_balance', 'last_balance', 'last_balance_at',
            'funding_factor', 'funding_factor_source',
            'raw_today_cost', 'today_cost', 'raw_total_cost', 'total_cost', 'today_cost_at'
        ]
        AND channel_projection_snapshot->>'id' IS NOT DISTINCT FROM channel_id::text
        AND channel_projection_snapshot->>'upstream_account_identity_revision'
            IS NOT DISTINCT FROM channel_identity_revision::text
        AND channel_projection_snapshot->>'cost_unit_epoch' IS NOT DISTINCT FROM cost_unit_epoch::text
        AND jsonb_typeof(channel_projection_snapshot->'funding_factor') IS NOT DISTINCT FROM 'number'
        AND (channel_projection_snapshot->>'funding_factor')::numeric = funding_factor_after
        AND channel_projection_snapshot->'raw_last_balance' IS NOT DISTINCT FROM cost_state_snapshot->'raw_balance'
        AND channel_projection_snapshot->'last_balance' IS NOT DISTINCT FROM cost_state_snapshot->'actual_inventory'
        AND channel_projection_snapshot->'last_balance_at' IS NOT DISTINCT FROM cost_state_snapshot->'balance_sampled_at'
        AND channel_projection_snapshot->'funding_factor' IS NOT DISTINCT FROM cost_state_snapshot->'funding_factor'
        AND channel_projection_snapshot->'funding_factor_source' IS NOT DISTINCT FROM cost_state_snapshot->'source'
        AND channel_projection_snapshot->'raw_today_cost' IS NOT DISTINCT FROM cost_state_snapshot->'raw_today_cost'
        AND channel_projection_snapshot->'today_cost' IS NOT DISTINCT FROM cost_state_snapshot->'actual_today_cost'
        AND channel_projection_snapshot->'raw_total_cost' IS NOT DISTINCT FROM cost_state_snapshot->'raw_total_cost'
        AND channel_projection_snapshot->'total_cost' IS NOT DISTINCT FROM cost_state_snapshot->'actual_total_cost'
        AND channel_projection_snapshot->'today_cost_at' IS NOT DISTINCT FROM cost_state_snapshot->'cost_sampled_at'
        AND cost_state_digest ~ '^[0-9a-f]{64}$'
        AND channel_projection_digest ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT channel_cost_unit_repair_adoptions_bounds CHECK (
        request_log_high_water > 0
        AND isfinite(cost_sampled_at_before)
        AND isfinite(cost_sampled_at_after)
        AND isfinite(affected_started_at)
        AND isfinite(affected_ended_at)
        AND cost_sampled_at_before < affected_started_at
        AND affected_started_at <= affected_ended_at
        AND affected_ended_at <= cost_sampled_at_after
    ),
    CONSTRAINT channel_cost_unit_repair_adoptions_factors CHECK (
        previous_provider_factor > 0 AND previous_provider_factor < 'Infinity'::numeric
        AND current_provider_factor > 0 AND current_provider_factor < 'Infinity'::numeric
        AND previous_provider_factor <> current_provider_factor
        AND funding_factor_before > 0 AND funding_factor_before < 'Infinity'::numeric
        AND funding_factor_after > 0 AND funding_factor_after < 'Infinity'::numeric
        AND funding_factor_before <> funding_factor_after
        AND abs(
            funding_factor_after * previous_provider_factor
            - funding_factor_before * current_provider_factor
        ) <= GREATEST(
            abs(funding_factor_after * previous_provider_factor),
            abs(funding_factor_before * current_provider_factor),
            1::numeric
        ) * 0.000000000001::numeric
        AND factor_source = 'advertised'
        AND isfinite(created_at)
    )
);

