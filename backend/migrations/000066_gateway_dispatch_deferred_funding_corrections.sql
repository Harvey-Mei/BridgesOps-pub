-- A retrospective funding correction can arrive before exact provider usage.
-- Preserve the dispatch-time factor and carry the later basis separately until
-- the provider supplies immutable raw cost.
CREATE TABLE public.gateway_request_funding_corrections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL,
    funding_event_id bigint NOT NULL,
    interval_start timestamp with time zone NOT NULL,
    -- NULL keeps the newest correction open through its commit boundary.
    -- Readers only apply rows newer than the frozen request basis, so a later
    -- cost-state version closes the projection without mutating history.
    interval_end timestamp with time zone,
    funding_factor numeric NOT NULL,
    cost_basis_version bigint NOT NULL,
    cost_basis_source character varying(32) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_gateway_request_funding_corrections_event UNIQUE (funding_event_id),
    CONSTRAINT fk_gateway_request_funding_corrections_event
        FOREIGN KEY (funding_event_id, channel_id)
        REFERENCES public.channel_funding_events(id, channel_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_gateway_request_funding_corrections_shape CHECK (
        channel_id > 0
        AND funding_event_id > 0
        AND isfinite(interval_start)
        AND (
            interval_end IS NULL
            OR (isfinite(interval_end) AND interval_start < interval_end)
        )
        AND funding_factor >= 0
        AND funding_factor::text NOT IN ('NaN', 'Infinity', '-Infinity')
        AND cost_basis_version > 0
        AND octet_length(btrim(cost_basis_source)) BETWEEN 1 AND 32
        AND isfinite(created_at)
    )
);

CREATE INDEX idx_gateway_request_funding_corrections_lookup
    ON public.gateway_request_funding_corrections (
        channel_id,
        interval_start,
        interval_end,
        cost_basis_version DESC,
        id DESC
    );

CREATE FUNCTION public.reject_gateway_request_funding_correction_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'gateway request funding correction is immutable'
        USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER trg_gateway_request_funding_correction_immutable
BEFORE UPDATE ON public.gateway_request_funding_corrections
FOR EACH ROW
EXECUTE FUNCTION public.reject_gateway_request_funding_correction_update();

ALTER TABLE public.gateway_request_logs
    ADD COLUMN funding_basis_at timestamp with time zone,
    ADD COLUMN deferred_funding_factor numeric,
    ADD COLUMN deferred_cost_basis_version bigint,
    ADD COLUMN deferred_cost_basis_source character varying(32),
    ADD CONSTRAINT chk_gateway_request_logs_funding_basis_at
        CHECK (funding_basis_at IS NULL OR isfinite(funding_basis_at)) NOT VALID,
    ADD CONSTRAINT chk_gateway_request_logs_deferred_funding_correction_shape
        CHECK (
            (
                deferred_funding_factor IS NULL
                AND deferred_cost_basis_version IS NULL
                AND deferred_cost_basis_source IS NULL
            )
            OR (
                deferred_funding_factor IS NOT NULL
                AND deferred_cost_basis_version IS NOT NULL
                AND deferred_cost_basis_source IS NOT NULL
                AND record_kind = 'dispatch_cost_evidence'
                AND price_fact_id IS NULL
                AND lower(btrim(COALESCE(cost_status, 'none'))) = 'none'
                AND raw_cost IS NULL
                AND btrim(COALESCE(upstream_usage_id, '')) = ''
                AND deferred_funding_factor >= 0
                AND deferred_funding_factor::text NOT IN ('NaN', 'Infinity', '-Infinity')
                AND deferred_cost_basis_version > 0
                AND octet_length(btrim(deferred_cost_basis_source)) BETWEEN 1 AND 32
            )
        ) NOT VALID;

CREATE FUNCTION public.reject_gateway_request_log_funding_basis_at_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.funding_basis_at IS DISTINCT FROM OLD.funding_basis_at THEN
        RAISE EXCEPTION 'gateway request log funding basis time is immutable'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_gateway_request_log_funding_basis_at_immutable
BEFORE UPDATE OF funding_basis_at ON public.gateway_request_logs
FOR EACH ROW
EXECUTE FUNCTION public.reject_gateway_request_log_funding_basis_at_update();

CREATE FUNCTION public.enforce_gateway_dispatch_deferred_funding_correction_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    old_has_tuple boolean;
    new_has_tuple boolean;
    old_tuple_complete boolean;
    new_tuple_complete boolean;
BEGIN
    new_has_tuple := NEW.deferred_funding_factor IS NOT NULL
        OR NEW.deferred_cost_basis_version IS NOT NULL
        OR NEW.deferred_cost_basis_source IS NOT NULL;
    new_tuple_complete := NEW.deferred_funding_factor IS NOT NULL
        AND NEW.deferred_cost_basis_version IS NOT NULL
        AND NEW.deferred_cost_basis_source IS NOT NULL;

    IF TG_OP = 'INSERT' THEN
        IF new_has_tuple THEN
            RAISE EXCEPTION 'dispatch evidence must start without a deferred funding correction'
                USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;

    old_has_tuple := OLD.deferred_funding_factor IS NOT NULL
        OR OLD.deferred_cost_basis_version IS NOT NULL
        OR OLD.deferred_cost_basis_source IS NOT NULL;
    old_tuple_complete := OLD.deferred_funding_factor IS NOT NULL
        AND OLD.deferred_cost_basis_version IS NOT NULL
        AND OLD.deferred_cost_basis_source IS NOT NULL;

    IF NEW.deferred_funding_factor IS NOT DISTINCT FROM OLD.deferred_funding_factor
       AND NEW.deferred_cost_basis_version IS NOT DISTINCT FROM OLD.deferred_cost_basis_version
       AND NEW.deferred_cost_basis_source IS NOT DISTINCT FROM OLD.deferred_cost_basis_source THEN
        RETURN NEW;
    END IF;

    -- Funding transactions may create or replace the complete tuple only while
    -- the row is still zero-cost provider-ID evidence.
    IF new_tuple_complete
       AND (NOT old_has_tuple OR old_tuple_complete)
       AND OLD.record_kind = 'dispatch_cost_evidence'
       AND NEW.record_kind = 'dispatch_cost_evidence'
       AND OLD.price_fact_id IS NULL
       AND NEW.price_fact_id IS NULL
       AND lower(btrim(COALESCE(OLD.cost_status, 'none'))) = 'none'
       AND lower(btrim(COALESCE(NEW.cost_status, 'none'))) = 'none'
       AND OLD.raw_cost IS NULL
       AND NEW.raw_cost IS NULL
       AND btrim(COALESCE(OLD.upstream_usage_id, '')) = ''
       AND btrim(COALESCE(NEW.upstream_usage_id, '')) = '' THEN
        RETURN NEW;
    END IF;

    -- Exact reconciliation consumes the tuple in its first v38-compatible
    -- update. A second update in the same transaction then converts raw cost to
    -- the consumed basis.
    IF old_tuple_complete
       AND NOT new_has_tuple
       AND OLD.record_kind = 'dispatch_cost_evidence'
       AND NEW.record_kind = 'dispatch_cost_evidence'
       AND OLD.price_fact_id IS NULL
       AND NEW.price_fact_id IS NULL
       AND lower(btrim(COALESCE(OLD.cost_status, 'none'))) = 'none'
       AND lower(btrim(COALESCE(NEW.cost_status, 'none'))) = 'reconciled'
       AND NEW.raw_cost IS NOT NULL
       AND btrim(COALESCE(NEW.upstream_usage_id, '')) <> '' THEN
        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'invalid dispatch evidence deferred funding correction transition'
        USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER trg_gateway_dispatch_deferred_funding_correction_transition
BEFORE INSERT OR UPDATE OF
    record_kind,
    cost_status,
    raw_cost,
    upstream_usage_id,
    deferred_funding_factor,
    deferred_cost_basis_version,
    deferred_cost_basis_source
ON public.gateway_request_logs
FOR EACH ROW
EXECUTE FUNCTION public.enforce_gateway_dispatch_deferred_funding_correction_transition();
