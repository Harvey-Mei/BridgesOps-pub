CREATE TABLE public.model_check_targets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL,
    channel_name character varying(128) NOT NULL,
    group_name character varying(128) NOT NULL,
    model_name character varying(256) NOT NULL,
    app character varying(32) NOT NULL,
    enabled boolean DEFAULT true NOT NULL,
    active boolean DEFAULT true NOT NULL,
    last_discovered_at timestamp with time zone NOT NULL,
    last_checked_at timestamp with time zone,
    last_status character varying(24) DEFAULT 'pending'::character varying NOT NULL,
    last_score numeric,
    baseline_score numeric,
    baseline_samples bigint DEFAULT 0 NOT NULL,
    recent_anomalies bigint DEFAULT 0 NOT NULL,
    consecutive_errors bigint DEFAULT 0 NOT NULL,
    alert_active boolean DEFAULT false NOT NULL,
    alert_reason text,
    alerted_at timestamp with time zone,
    recovered_at timestamp with time zone,
    last_actual_model character varying(256),
    last_error text,
    created_at timestamp with time zone,
    updated_at timestamp with time zone
);

CREATE UNIQUE INDEX idx_model_check_target
    ON public.model_check_targets (channel_id, group_name, model_name, app);
CREATE INDEX idx_model_check_due
    ON public.model_check_targets (enabled, active, last_checked_at);
CREATE INDEX idx_model_check_channel_alert
    ON public.model_check_targets (channel_id, last_status, alert_active);

CREATE TABLE public.model_check_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_id bigint NOT NULL,
    channel_id bigint NOT NULL,
    channel_name character varying(128) NOT NULL,
    group_name character varying(128) NOT NULL,
    model_name character varying(256) NOT NULL,
    actual_model character varying(256),
    app character varying(32) NOT NULL,
    probe_version character varying(32) NOT NULL,
    status character varying(24) NOT NULL,
    score numeric DEFAULT 0 NOT NULL,
    baseline_before numeric,
    hard_mismatch boolean DEFAULT false NOT NULL,
    anomaly_reasons text,
    evidence_json text NOT NULL,
    request_count bigint DEFAULT 0 NOT NULL,
    prompt_tokens bigint DEFAULT 0 NOT NULL,
    completion_tokens bigint DEFAULT 0 NOT NULL,
    cache_read_tokens bigint DEFAULT 0 NOT NULL,
    total_tokens bigint DEFAULT 0 NOT NULL,
    first_byte_ms bigint DEFAULT 0 NOT NULL,
    latency_ms bigint DEFAULT 0 NOT NULL,
    error text,
    started_at timestamp with time zone NOT NULL,
    finished_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone
);

CREATE INDEX idx_model_check_runs_target_time
    ON public.model_check_runs (target_id, finished_at);
CREATE INDEX idx_model_check_runs_channel_id ON public.model_check_runs (channel_id);
CREATE INDEX idx_model_check_runs_status ON public.model_check_runs (status);
CREATE INDEX idx_model_check_runs_finished_at ON public.model_check_runs (finished_at);
