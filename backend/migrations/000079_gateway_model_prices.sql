-- Stamp every audit with the actual inserting transaction. The catalog's
-- deferred trigger uses this to prevent an old or pre-seeded audit from
-- authorizing a later mutation.
CREATE FUNCTION public.stamp_gateway_model_price_audit_transaction()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.transaction_id := txid_current();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_gateway_model_price_audits_stamp_transaction
BEFORE INSERT ON public.gateway_model_price_audits
