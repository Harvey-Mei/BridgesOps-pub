-- Administrator-maintained model prices are reusable catalog inputs. They are
-- deliberately separate from immutable request price facts, which bind the
-- catalog value to the exact channel/group/key generation selected at dispatch.
CREATE TABLE public.gateway_model_prices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name character varying(256) NOT NULL,
    input_unit_price_usd double precision NOT NULL,
    output_unit_price_usd double precision NOT NULL,
    cache_read_unit_price_usd double precision,
    cache_write_unit_price_usd double precision,
    long_context_threshold_tokens bigint,
    long_context_input_unit_price_usd double precision,
    long_context_output_unit_price_usd double precision,
    long_context_cache_read_unit_price_usd double precision,
    long_context_cache_write_unit_price_usd double precision,
    source character varying(32) NOT NULL DEFAULT 'manual',
    source_url character varying(512) NOT NULL DEFAULT '',
    source_checksum character varying(64) NOT NULL DEFAULT '',
    source_observed_at timestamp(6) with time zone,
    auto_update boolean NOT NULL DEFAULT false,
    enabled boolean NOT NULL DEFAULT true,
    revision bigint NOT NULL DEFAULT 1,
    created_at timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_gateway_model_prices_model_name UNIQUE (model_name),
    CONSTRAINT chk_gateway_model_prices_model_name
        CHECK (model_name = btrim(model_name) AND model_name <> ''),
    CONSTRAINT chk_gateway_model_prices_values
        CHECK (
            input_unit_price_usd >= 0
            AND output_unit_price_usd >= 0
            AND input_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            AND output_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            AND (cache_read_unit_price_usd IS NULL OR (
                cache_read_unit_price_usd >= 0
                AND cache_read_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            ))
            AND (cache_write_unit_price_usd IS NULL OR (
                cache_write_unit_price_usd >= 0
                AND cache_write_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
            ))
        ),
    CONSTRAINT chk_gateway_model_prices_long_context
        CHECK (
            (
                long_context_threshold_tokens IS NULL
                AND long_context_input_unit_price_usd IS NULL
                AND long_context_output_unit_price_usd IS NULL
                AND long_context_cache_read_unit_price_usd IS NULL
                AND long_context_cache_write_unit_price_usd IS NULL
            )
            OR (
                long_context_threshold_tokens = 272000
                AND long_context_input_unit_price_usd IS NOT NULL
                AND long_context_output_unit_price_usd IS NOT NULL
                AND long_context_input_unit_price_usd >= 0
                AND long_context_output_unit_price_usd >= 0
                AND long_context_input_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
                AND long_context_output_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
                AND (long_context_cache_read_unit_price_usd IS NULL OR (
                    long_context_cache_read_unit_price_usd >= 0
                    AND long_context_cache_read_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
                ))
                AND (long_context_cache_write_unit_price_usd IS NULL OR (
                    long_context_cache_write_unit_price_usd >= 0
                    AND long_context_cache_write_unit_price_usd::text NOT IN ('NaN', 'Infinity', '-Infinity')
                ))
            )
        ),
    CONSTRAINT chk_gateway_model_prices_source
        CHECK (
            source IN ('manual', 'litellm')
            AND source_url = btrim(source_url)
            AND source_checksum = lower(source_checksum)
            AND (source_checksum = '' OR source_checksum ~ '^[0-9a-f]{64}$')
            AND (source <> 'litellm' OR (source_url <> '' AND source_checksum <> '' AND source_observed_at IS NOT NULL))
            AND (source_observed_at IS NULL OR isfinite(source_observed_at))
        ),
    CONSTRAINT chk_gateway_model_prices_revision CHECK (revision > 0),
    CONSTRAINT chk_gateway_model_prices_times
        CHECK (isfinite(created_at) AND isfinite(updated_at) AND updated_at >= created_at)
);

CREATE INDEX idx_gateway_model_prices_enabled_model
    ON public.gateway_model_prices (enabled, model_name);

-- Observation watermarks are deliberately independent from catalog revisions.
-- A newer source snapshot can confirm an unchanged price without manufacturing
-- an audit revision, while still fencing a delayed older snapshot in another
-- server process from restoring stale values.
CREATE TABLE public.gateway_model_price_source_watermarks (
    model_name character varying(256) NOT NULL,
    source character varying(32) NOT NULL,
    source_url character varying(512) NOT NULL,
    source_checksum character varying(64) NOT NULL,
    source_observed_at timestamp(6) with time zone NOT NULL,
    created_at timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (model_name, source),
    CONSTRAINT chk_gateway_model_price_watermarks_model_name
        CHECK (model_name = btrim(model_name) AND model_name <> ''),
    CONSTRAINT chk_gateway_model_price_watermarks_source
        CHECK (
            source = 'litellm'
            AND source_url = btrim(source_url)
            AND source_url <> ''
            AND source_checksum = lower(source_checksum)
            AND source_checksum ~ '^[0-9a-f]{64}$'
        ),
    CONSTRAINT chk_gateway_model_price_watermarks_times
        CHECK (
            isfinite(source_observed_at)
            AND isfinite(created_at)
            AND isfinite(updated_at)
            AND updated_at >= created_at
        )
);

