-- A deferred constraint lets the application write the catalog row and its
-- audit in either order inside one transaction, while still making an
-- unaudited direct SQL mutation impossible to commit.
CREATE FUNCTION public.require_gateway_model_price_audit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    audit_found boolean;
BEGIN
    IF TG_OP = 'INSERT' THEN
        SELECT EXISTS (
            SELECT 1
            FROM public.gateway_model_price_audits AS audit
            WHERE audit.model_price_id = NEW.id
              AND audit.action = 'create'
              AND audit.revision = NEW.revision
              AND audit.model_name = NEW.model_name
              AND audit.input_unit_price_usd = NEW.input_unit_price_usd
              AND audit.output_unit_price_usd = NEW.output_unit_price_usd
              AND audit.cache_read_unit_price_usd IS NOT DISTINCT FROM NEW.cache_read_unit_price_usd
              AND audit.cache_write_unit_price_usd IS NOT DISTINCT FROM NEW.cache_write_unit_price_usd
              AND audit.long_context_threshold_tokens IS NOT DISTINCT FROM NEW.long_context_threshold_tokens
              AND audit.long_context_input_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_input_unit_price_usd
              AND audit.long_context_output_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_output_unit_price_usd
              AND audit.long_context_cache_read_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_cache_read_unit_price_usd
              AND audit.long_context_cache_write_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_cache_write_unit_price_usd
              AND audit.source = NEW.source
              AND audit.source_url = NEW.source_url
              AND audit.source_checksum = NEW.source_checksum
              AND audit.source_observed_at IS NOT DISTINCT FROM NEW.source_observed_at
              AND audit.auto_update = NEW.auto_update
              AND audit.enabled = NEW.enabled
              AND audit.transaction_id = txid_current()
              AND NEW.revision = 1
              AND NOT EXISTS (
                  SELECT 1
                  FROM public.gateway_model_price_audits AS history
                  WHERE history.model_price_id = NEW.id
                    AND history.id <> audit.id
              )
        ) INTO audit_found;
    ELSIF TG_OP = 'UPDATE' THEN
        IF OLD.revision >= 9223372036854775807
            OR NEW.id <> OLD.id
            OR NEW.revision <> OLD.revision + 1
            OR NEW.created_at <> OLD.created_at
            OR NEW.updated_at < OLD.updated_at THEN
            audit_found := false;
        ELSE
            SELECT EXISTS (
                SELECT 1
                FROM public.gateway_model_price_audits AS audit
                WHERE audit.model_price_id = NEW.id
                  AND audit.action = 'update'
                  AND audit.revision = NEW.revision
                  AND audit.model_name = NEW.model_name
                  AND audit.input_unit_price_usd = NEW.input_unit_price_usd
                  AND audit.output_unit_price_usd = NEW.output_unit_price_usd
                  AND audit.cache_read_unit_price_usd IS NOT DISTINCT FROM NEW.cache_read_unit_price_usd
                  AND audit.cache_write_unit_price_usd IS NOT DISTINCT FROM NEW.cache_write_unit_price_usd
                  AND audit.long_context_threshold_tokens IS NOT DISTINCT FROM NEW.long_context_threshold_tokens
                  AND audit.long_context_input_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_input_unit_price_usd
                  AND audit.long_context_output_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_output_unit_price_usd
                  AND audit.long_context_cache_read_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_cache_read_unit_price_usd
                  AND audit.long_context_cache_write_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_cache_write_unit_price_usd
                  AND audit.source = NEW.source
                  AND audit.source_url = NEW.source_url
                  AND audit.source_checksum = NEW.source_checksum
                  AND audit.source_observed_at IS NOT DISTINCT FROM NEW.source_observed_at
                  AND audit.auto_update = NEW.auto_update
                  AND audit.enabled = NEW.enabled
                  AND audit.transaction_id = txid_current()
            ) INTO audit_found;
        END IF;
    ELSE
        IF OLD.revision >= 9223372036854775807 THEN
            audit_found := false;
        ELSE
            SELECT EXISTS (
                SELECT 1
                FROM public.gateway_model_price_audits AS audit
                WHERE audit.model_price_id = OLD.id
                  AND audit.action = 'delete'
                  AND audit.revision = OLD.revision + 1
                  AND audit.model_name = OLD.model_name
                  AND audit.input_unit_price_usd = OLD.input_unit_price_usd
                  AND audit.output_unit_price_usd = OLD.output_unit_price_usd
                  AND audit.cache_read_unit_price_usd IS NOT DISTINCT FROM OLD.cache_read_unit_price_usd
                  AND audit.cache_write_unit_price_usd IS NOT DISTINCT FROM OLD.cache_write_unit_price_usd
                  AND audit.long_context_threshold_tokens IS NOT DISTINCT FROM OLD.long_context_threshold_tokens
                  AND audit.long_context_input_unit_price_usd IS NOT DISTINCT FROM OLD.long_context_input_unit_price_usd
                  AND audit.long_context_output_unit_price_usd IS NOT DISTINCT FROM OLD.long_context_output_unit_price_usd
                  AND audit.long_context_cache_read_unit_price_usd IS NOT DISTINCT FROM OLD.long_context_cache_read_unit_price_usd
                  AND audit.long_context_cache_write_unit_price_usd IS NOT DISTINCT FROM OLD.long_context_cache_write_unit_price_usd
                  AND audit.source = OLD.source
                  AND audit.source_url = OLD.source_url
                  AND audit.source_checksum = OLD.source_checksum
                  AND audit.source_observed_at IS NOT DISTINCT FROM OLD.source_observed_at
                  AND audit.auto_update = OLD.auto_update
                  AND audit.enabled = OLD.enabled
                  AND audit.transaction_id = txid_current()
            ) INTO audit_found;
        END IF;
    END IF;

    IF NOT audit_found THEN
        RAISE EXCEPTION 'gateway model price catalog mutation requires a matching audit'
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;

-- The reciprocal deferred check rejects orphan/pre-seeded audits. A create or
-- update audit must describe the catalog row committed by this transaction; a
-- delete audit must follow the immediately preceding revision and leave no
-- catalog row behind.
CREATE FUNCTION public.require_gateway_model_price_catalog_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    transition_found boolean;
BEGIN
    IF NEW.transaction_id <> txid_current() THEN
        transition_found := false;
    ELSIF NEW.action IN ('create', 'update') THEN
        SELECT EXISTS (
            SELECT 1
            FROM public.gateway_model_prices AS price
            WHERE price.id = NEW.model_price_id
              AND price.revision = NEW.revision
              AND price.model_name = NEW.model_name
              AND price.input_unit_price_usd = NEW.input_unit_price_usd
              AND price.output_unit_price_usd = NEW.output_unit_price_usd
              AND price.cache_read_unit_price_usd IS NOT DISTINCT FROM NEW.cache_read_unit_price_usd
              AND price.cache_write_unit_price_usd IS NOT DISTINCT FROM NEW.cache_write_unit_price_usd
              AND price.long_context_threshold_tokens IS NOT DISTINCT FROM NEW.long_context_threshold_tokens
              AND price.long_context_input_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_input_unit_price_usd
              AND price.long_context_output_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_output_unit_price_usd
              AND price.long_context_cache_read_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_cache_read_unit_price_usd
              AND price.long_context_cache_write_unit_price_usd IS NOT DISTINCT FROM NEW.long_context_cache_write_unit_price_usd
              AND price.source = NEW.source
              AND price.source_url = NEW.source_url
              AND price.source_checksum = NEW.source_checksum
              AND price.source_observed_at IS NOT DISTINCT FROM NEW.source_observed_at
              AND price.auto_update = NEW.auto_update
              AND price.enabled = NEW.enabled
              AND (
                  NEW.action = 'create'
                  OR EXISTS (
                      SELECT 1
                      FROM public.gateway_model_price_audits AS previous
                      WHERE previous.model_price_id = NEW.model_price_id
                        AND previous.revision = NEW.revision - 1
                        AND previous.action IN ('create', 'update')
                  )
              )
        ) INTO transition_found;
    ELSE
        SELECT NOT EXISTS (
            SELECT 1
            FROM public.gateway_model_prices AS price
            WHERE price.id = NEW.model_price_id
        ) AND EXISTS (
            SELECT 1
            FROM public.gateway_model_price_audits AS previous
            WHERE previous.model_price_id = NEW.model_price_id
              AND previous.revision = NEW.revision - 1
              AND previous.action IN ('create', 'update')
        ) INTO transition_found;
    END IF;

    IF NOT transition_found THEN
        RAISE EXCEPTION 'gateway model price audit requires its catalog transition'
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_gateway_model_prices_require_audit
AFTER INSERT OR UPDATE OR DELETE ON public.gateway_model_prices
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION public.require_gateway_model_price_audit();

