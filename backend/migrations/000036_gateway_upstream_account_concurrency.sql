-- 000035 is reserved for managed-key provenance. Keep this migration at
-- 000036 so the two independently reviewed changes retain a stable order.

ALTER TABLE public.channels
    ADD COLUMN upstream_account_identity_revision bigint NOT NULL DEFAULT 1,
    ADD COLUMN admin_revision bigint NOT NULL DEFAULT 1,
    ADD CONSTRAINT chk_channels_upstream_account_identity_revision
        CHECK (upstream_account_identity_revision > 0),
    ADD CONSTRAINT chk_channels_admin_revision
        CHECK (admin_revision > 0),
    ADD CONSTRAINT uq_channels_id_type_account_revision
        UNIQUE (id, type, upstream_account_identity_revision);

CREATE TABLE public.gateway_upstream_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider character varying(32) NOT NULL,
    api_origin_hash character(64) NOT NULL,
    external_account_id_hash character(64) NOT NULL,
    concurrency_limit integer,
    concurrency_scope character varying(32) NOT NULL DEFAULT 'account',
    concurrency_source character varying(128),
    concurrency_observed_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_gateway_upstream_account_identity
        UNIQUE (provider, api_origin_hash, external_account_id_hash),
    CONSTRAINT uq_gateway_upstream_account_id_provider
        UNIQUE (id, provider),
    CONSTRAINT chk_gateway_upstream_account_provider
        CHECK (provider IN ('sub2api')),
    CONSTRAINT chk_gateway_upstream_account_origin_hash
        CHECK (api_origin_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_gateway_upstream_account_external_id_hash
        CHECK (external_account_id_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_gateway_upstream_account_scope
        CHECK (concurrency_scope = 'account'),
    CONSTRAINT chk_gateway_upstream_account_limit
        CHECK (concurrency_limit IS NULL OR concurrency_limit >= 0),
    CONSTRAINT chk_gateway_upstream_account_fact_complete
        CHECK (
            (concurrency_limit IS NULL AND concurrency_source IS NULL AND concurrency_observed_at IS NULL)
            OR
            (concurrency_limit IS NOT NULL AND concurrency_source IS NOT NULL AND length(btrim(concurrency_source)) > 0 AND concurrency_observed_at IS NOT NULL)
        )
);

CREATE TABLE public.gateway_channel_upstream_account_bindings (
    channel_id bigint PRIMARY KEY,
    provider character varying(32) NOT NULL,
    channel_identity_revision bigint NOT NULL,
    upstream_account_id bigint NOT NULL,
    source character varying(128) NOT NULL,
    observed_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_gateway_channel_account_source
        CHECK (length(btrim(source)) > 0),
    CONSTRAINT chk_gateway_channel_account_identity_revision
        CHECK (channel_identity_revision > 0),
    CONSTRAINT fk_gateway_channel_account_channel_identity
        FOREIGN KEY (channel_id, provider, channel_identity_revision)
        REFERENCES public.channels(id, type, upstream_account_identity_revision)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT fk_gateway_channel_account_account_provider
        FOREIGN KEY (upstream_account_id, provider)
        REFERENCES public.gateway_upstream_accounts(id, provider)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX idx_gateway_channel_account_account
    ON public.gateway_channel_upstream_account_bindings (upstream_account_id, channel_id);

CREATE TABLE public.gateway_channel_upstream_account_binding_audits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL,
    provider character varying(32) NOT NULL,
    channel_identity_revision bigint NOT NULL,
    previous_upstream_account_id bigint,
    upstream_account_id bigint NOT NULL,
    source character varying(128) NOT NULL,
    observed_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_gateway_channel_account_audit_channel
        CHECK (channel_id > 0),
    CONSTRAINT chk_gateway_channel_account_audit_provider
        CHECK (provider IN ('sub2api')),
    CONSTRAINT chk_gateway_channel_account_audit_identity_revision
        CHECK (channel_identity_revision > 0),
    CONSTRAINT chk_gateway_channel_account_audit_source
        CHECK (length(btrim(source)) > 0)
);

CREATE INDEX idx_gateway_channel_account_audit_channel
    ON public.gateway_channel_upstream_account_binding_audits (channel_id, created_at DESC, id DESC);
