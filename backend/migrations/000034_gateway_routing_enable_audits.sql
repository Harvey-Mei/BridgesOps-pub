CREATE TABLE public.gateway_routing_enable_audits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upstream_group_id bigint NOT NULL,
    channel_id bigint NOT NULL,
    canonical_group_name character varying(128) NOT NULL,
    presence_generation bigint NOT NULL,
    actor character varying(128) NOT NULL,
    idempotency_key character varying(128) NOT NULL,
    reason character varying(256) NOT NULL,
    changed boolean NOT NULL DEFAULT false,
    previous_failure_kind character varying(32) NOT NULL DEFAULT '',
    previous_failure_status integer NOT NULL DEFAULT 0,
    previous_failure_count integer NOT NULL DEFAULT 0,
    previous_failure_at timestamp with time zone,
    previous_cooldown_until timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_gateway_routing_enable_group CHECK (upstream_group_id > 0 AND channel_id > 0),
    CONSTRAINT chk_gateway_routing_enable_generation CHECK (presence_generation > 0),
    CONSTRAINT chk_gateway_routing_enable_actor CHECK (length(btrim(actor)) > 0),
    CONSTRAINT chk_gateway_routing_enable_idempotency CHECK (length(btrim(idempotency_key)) > 0),
    CONSTRAINT chk_gateway_routing_enable_reason CHECK (length(btrim(reason)) > 0),
    CONSTRAINT uq_gateway_routing_enable_idempotency
        UNIQUE (upstream_group_id, presence_generation, idempotency_key)
);

CREATE INDEX idx_gateway_routing_enable_group_created
    ON public.gateway_routing_enable_audits (upstream_group_id, presence_generation, created_at DESC);

CREATE INDEX idx_gateway_routing_enable_channel_created
    ON public.gateway_routing_enable_audits (channel_id, created_at DESC);
