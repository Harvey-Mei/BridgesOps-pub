CREATE TABLE public.gateway_managed_key_rebuild_intents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL,
    channel_identity_revision bigint NOT NULL,
    upstream_group_id bigint NOT NULL,
    presence_generation bigint NOT NULL,
    canonical_group_name character varying(128) NOT NULL,
    local_key_id bigint NOT NULL,
    upstream_key_id bigint NOT NULL,
    upstream_key_name character varying(128) NOT NULL,
    claim_key character varying(64) NOT NULL,
    evidence_digest character varying(64) NOT NULL,
    ownership_claim character varying(64) NOT NULL,
    status character varying(16) NOT NULL DEFAULT 'processing',
    detected_at timestamp with time zone NOT NULL,
    resolved_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_gateway_managed_key_rebuild_intent_status
        CHECK (status IN ('processing', 'acknowledged', 'manual_review')),
    CONSTRAINT chk_gateway_managed_key_rebuild_intent_generation
        CHECK (presence_generation > 0),
    CONSTRAINT chk_gateway_managed_key_rebuild_intent_channel_revision
        CHECK (channel_identity_revision > 0),
    CONSTRAINT chk_gateway_managed_key_rebuild_intent_remote_id
        CHECK (upstream_key_id > 0),
    CONSTRAINT chk_gateway_managed_key_rebuild_intent_digests
        CHECK (length(claim_key) = 64 AND length(evidence_digest) = 64 AND length(ownership_claim) = 64)
);

CREATE UNIQUE INDEX idx_gateway_managed_key_rebuild_intent_claim
    ON public.gateway_managed_key_rebuild_intents (claim_key);

CREATE INDEX idx_gateway_managed_key_rebuild_intent_reconcile
    ON public.gateway_managed_key_rebuild_intents (channel_id, channel_identity_revision, status, id);
