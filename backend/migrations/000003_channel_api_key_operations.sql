CREATE TABLE public.channel_api_key_operations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL,
    provider character varying(32) NOT NULL,
    scope_hash character varying(64) NOT NULL,
    request_fingerprint character varying(64) NOT NULL,
    managed_name character varying(256) NOT NULL,
    group_identity character varying(256) NOT NULL,
    custom_key_hash character varying(64),
    status character varying(24) DEFAULT 'pending'::character varying NOT NULL,
    remote_id bigint,
    completed_at timestamp with time zone,
    created_at timestamp with time zone,
    updated_at timestamp with time zone
);

CREATE UNIQUE INDEX idx_channel_api_key_operation_scope
    ON public.channel_api_key_operations (channel_id, provider, scope_hash);
CREATE UNIQUE INDEX idx_channel_api_key_operation_remote
    ON public.channel_api_key_operations (channel_id, provider, remote_id);
